<#
.SYNOPSIS
    Validates the Adaptive Card payload generated by send_adaptive_card.py.

.DESCRIPTION
    Runs the sender in --dump mode and checks that the produced JSON matches
    the structure expected by a Power Automate "Post card in a chat or channel"
    workflow.
#>
[CmdletBinding()]
param(
    [string]$Title = "Test title",
    [string]$Message = "Test message body"
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$scriptPath = Join-Path $repoRoot "send_adaptive_card.py"

if (-not (Test-Path $scriptPath)) {
    throw "send_adaptive_card.py not found at $scriptPath"
}

$python = Get-Command python -ErrorAction SilentlyContinue
if (-not $python) {
    $python = Get-Command python3 -ErrorAction SilentlyContinue
}
if (-not $python) {
    throw "Python is required to validate the payload."
}

Write-Host "Generating payload with $Title / $Message ..."
$output = & $python.Source $scriptPath "https://example.com/webhook" $Title $Message "--dump"
if ($LASTEXITCODE -ne 0) {
    throw "Payload generation failed with exit code $LASTEXITCODE"
}

$payload = $output | ConvertFrom-Json

# Validate top-level structure
if ($payload.type -ne "message") {
    throw "Expected payload.type to be 'message' but got '$($payload.type)'"
}
if (-not $payload.attachments -or $payload.attachments.Count -ne 1) {
    throw "Expected exactly one attachment"
}

$attachment = $payload.attachments[0]
if ($attachment.contentType -ne "application/vnd.microsoft.card.adaptive") {
    throw "Unexpected contentType: $($attachment.contentType)"
}

$card = $attachment.content
if ($card.type -ne "AdaptiveCard") {
    throw "Expected card.type to be 'AdaptiveCard' but got '$($card.type)'"
}
if ($card.version -ne "1.4") {
    throw "Expected card.version to be '1.4' but got '$($card.version)'"
}
if ($card.msTeams.width -ne "full") {
    throw "Expected msTeams.width to be 'full' but got '$($card.msTeams.width)'"
}
if ($card.body.Count -ne 2) {
    throw "Expected 2 body elements but got $($card.body.Count)"
}
if ($card.body[0].text -ne $Title) {
    throw "Title mismatch"
}
if ($card.body[1].text -ne $Message) {
    throw "Message mismatch"
}

Write-Host "Payload validation passed." -ForegroundColor Green
